/**
 * What the adapters read off a platform, before it is rendered for the bot (`render.ts`). Every field
 * is what the page or the platform's own data said; nothing is inferred.
 */

export const PLATFORM_IDS = ['reddit', 'x', 'facebook', 'threads', 'instagram', 'youtube', 'bilibili', 'rednote', 'substack'] as const;
export type PlatformId = (typeof PLATFORM_IDS)[number];

/** Video platforms list videos; the others list posts and leave video posts out. */
export const VIDEO_PLATFORMS: ReadonlySet<PlatformId> = new Set(['youtube', 'bilibili']);

/**
 * Where a listing comes from: the platform's own feed (home or recommended), a search, one account's
 * posts, or a community (a subreddit, a Facebook group).
 */
export type SourceKind = 'feed' | 'search' | 'account' | 'community';

/** Images read per post; the rest are marked `cap`. */
export const IMAGES_PER_POST = 4;
/** Images attached per call when the model reads them; past this they are read with OCR. */
export const ATTACHED_MAX = 6;

export interface ImageRef {
  url: string;
  /** The platform's own description of the image, when it has one. */
  alt?: string;
  /** What became of the image when posts were read; absent when it was not looked at. */
  read?: ImageRead;
}

/** OCR text ('' when it found none), an image attached for the model, or why the image was not read. */
export type ImageRead =
  | { kind: 'ocr'; text: string }
  | { kind: 'attached'; n: number }
  | { kind: 'unread'; why: 'time' | 'cap' | 'download' | 'decode' | 'ocr' };

export interface Post {
  platform: PlatformId;
  /** The platform's id for the post or video, or its URL when the page gave no id. */
  id: string;
  url: string;
  author?: string;
  /** Subreddit, group or channel the post is in, when it is not the author's own page. */
  community?: string;
  title?: string;
  text: string;
  /** ISO time when the platform gave an exact one. */
  publishedAt?: string;
  /** The platform's relative time ("3 hours ago") when it gave no exact one. */
  publishedText?: string;
  /** Counts with their label (points, comments, likes, views); the label is empty when the value carries its own word. */
  stats: Array<[label: string, value: string]>;
  images: ImageRef[];
  /** The post carries a video (on a video platform, the post is the video). */
  video: boolean;
  /** Video length as the platform shows it. */
  duration?: string;
  /** Read by the platform's adapter, or by the generic reader after the adapter found nothing. */
  extraction: 'adapter' | 'generic';
}

export interface Comment {
  author?: string;
  text: string;
  /** Score or likes as the platform labels them. */
  score?: string;
}

export interface TranscriptLine {
  /** Seconds from the start of the video. */
  startSec: number;
  text: string;
}

export interface Transcript {
  platform: PlatformId;
  id: string;
  url: string;
  title?: string;
  author?: string;
  duration?: string;
  /** Language of the captions as the platform names it. */
  language?: string;
  /** Captions generated by the platform's speech recognition. */
  generated: boolean;
  lines: TranscriptLine[];
}

/** Joins whitespace runs and trims; platforms pad text with layout whitespace. */
export const clean = (s: string | null | undefined): string => (s ?? '').replace(/[ \t ]+/g, ' ').replace(/\s*\n\s*/g, '\n').trim();

/** Tesseract spaces out CJK characters; this joins them back. */
export const joinCjk = (s: string): string =>
  s.replace(/([　-〿぀-ヿ㐀-鿿가-힯＀-￯])[ ]+(?=[　-〿぀-ヿ㐀-鿿가-힯＀-￯])/g, '$1');
